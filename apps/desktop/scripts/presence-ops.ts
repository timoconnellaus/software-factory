// The operations a desktop presence proof can decide, as Swift for the key helper (spec 40 M4b):
// `sign` refuses a presence message for any other op. The Swift file is generated and checked in;
// test/keys-helper.test.ts fails when it no longer matches the registry, and rewrites it with
//
//   SF_WRITE_PRESENCE_OPS=1 pnpm --filter @software-factory/desktop exec vitest run test/keys-helper.test.ts
import { OPERATIONS, presenceSurfaceAllowed } from "@software-factory/core";

export function desktopPresenceOps(): string[] {
  return OPERATIONS.filter((op) => presenceSurfaceAllowed(op, "desktop"))
    .map((op) => op.name)
    .sort();
}

export function presenceOpsSwift(ops: string[]): string {
  return [
    "// Generated by apps/desktop/scripts/presence-ops.ts from the operations registry: do not edit.",
    "// The operations a desktop presence proof can decide (presenceSurfaceAllowed, ADR 0391).",
    "public let presenceOps: Set<String> = [",
    ...ops.map((op) => `  "${op}",`),
    "]",
    "",
  ].join("\n");
}

export const PRESENCE_OPS_SWIFT = "native/sf-keys-app/Sources/SFKeysCore/PresenceOps.swift";
